#!/usr/bin/env bash
# Lint AGENTS.md files and the ADR index (PLAN.md section 9.3).
# Usage: scripts/check-docs.sh [--fix]   (--fix rewrites docs/decisions/README.md)
set -euo pipefail

cd "$(dirname "$0")/.."
fix=0
[ "${1:-}" = "--fix" ] && fix=1

fails=0
fail() { echo "check-docs: FAIL: $*" >&2; fails=$((fails + 1)); }

# Generated ADR index, printed to stdout.
index() {
  echo "# Decisions"
  echo
  echo "Generated by scripts/check-docs.sh --fix. Do not edit."
  echo
  local f title status
  for f in docs/decisions/[0-9][0-9][0-9][0-9]-*.md; do
    [ -e "$f" ] || continue
    title=$(sed -n '1s/^# //p' "$f")
    status=$(sed -n 's/^Status: *//p' "$f" | head -n 1)
    echo "- [$title]($(basename "$f")) - $status"
  done
}

# Backticked tokens of a file, one per line, without the backticks.
ticks() { { grep -o '`[^`]*`' "$1" || true; } | tr -d '`'; }

make_targets=""
[ -f Makefile ] && make_targets=$(grep -oE '^[A-Za-z0-9_.-]+:' Makefile | tr -d ':' || true)

now_idx=$(( $(date +%Y) * 12 + 10#$(date +%m) ))

while IFS= read -r f; do
  dir=$(dirname "$f")
  cap=80
  [ "$f" = "./AGENTS.md" ] && cap=150
  n=$(wc -l < "$f" | tr -d ' ')
  [ "$n" -le "$cap" ] || fail "$f has $n lines, cap is $cap"

  while IFS= read -r tok; do
    [ -n "$tok" ] || continue
    # `make a b` lists targets.
    case "$tok" in
      "make "*)
        for t in ${tok#make }; do
          printf '%s\n' "$make_targets" | grep -qx -- "$t" || fail "$f: make target '$t' is not in Makefile"
        done
        continue ;;
    esac
    case "$tok" in
      "~"*|'$'*|-*|http*|*" "*|*"*"*|*"<"*|*"{"*) continue ;;
      */*|*.rs|*.ts|*.tsx|*.md|*.sh|*.toml|*.json|*.css) ;;
      *) continue ;;
    esac
    if [ ! -e "$tok" ] && [ ! -e "$dir/$tok" ]; then
      fail "$f: path '$tok' does not exist"
    fi
  done <<< "$(ticks "$f")"

  while IFS= read -r num; do
    [ -n "$num" ] || continue
    adr=$(ls docs/decisions/"$num"-*.md 2>/dev/null | head -n 1 || true)
    if [ -z "$adr" ]; then
      fail "$f: ADR $num has no file in docs/decisions/"
    elif sed -n 's/^Status: *//p' "$adr" | head -n 1 | grep -q 'Superseded'; then
      fail "$f: references ADR $num, which is superseded"
    fi
  done <<< "$({ grep -o 'ADR [0-9]\{4\}' "$f" || true; } | sed 's/ADR //' | sort -u)"

  # Lessons: every bullet carries a (YYYY-MM) stamp; old stamps warn.
  while IFS= read -r line; do
    [ -n "$line" ] || continue  # a here-string of empty output is one empty line
    stamp=$(printf '%s\n' "$line" | sed -n 's/.*(\([0-9]\{4\}-[0-9]\{2\}\))$/\1/p')
    if [ -z "$stamp" ]; then
      fail "$f: lesson lacks a trailing (YYYY-MM) stamp: $line"
      continue
    fi
    idx=$(( ${stamp%-*} * 12 + 10#${stamp#*-} ))
    [ $((now_idx - idx)) -le 3 ] || echo "check-docs: warning: $f: lesson older than 90 days, re-verify: $line" >&2
  done <<< "$(awk '/^## /{in_l = ($0 == "## Lessons"); next} in_l && /^- /' "$f")"
done <<< "$(find . -name AGENTS.md -not -path './target/*' -not -path '*/node_modules/*' | sort)"

if [ "$fix" -eq 1 ]; then
  index > docs/decisions/README.md
elif [ "$(index)" != "$(cat docs/decisions/README.md 2>/dev/null || true)" ]; then
  fail "docs/decisions/README.md is stale, run scripts/check-docs.sh --fix"
fi

if [ "$fails" -gt 0 ]; then
  echo "check-docs: $fails failure(s)" >&2
  exit 1
fi
echo "check-docs: ok"
